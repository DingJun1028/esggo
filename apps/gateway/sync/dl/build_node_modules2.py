import os
import json
import shutil
import subprocess

SYNC = os.path.abspath("C:/Project/esggo/apps/gateway/sync")
DL = os.path.join(SYNC, "dl")
EXTRACT = os.path.join(SYNC, "dl", "_extract")
DEST = os.path.join(SYNC, "node_modules")

os.makedirs(EXTRACT, exist_ok=True)
if os.path.exists(DEST):
    shutil.rmtree(DEST)
os.makedirs(DEST, exist_ok=True)

tarballs = sorted(f for f in os.listdir(DL) if f.endswith(".tgz"))
print(f"處理 {len(tarballs)} 個 tarball")

for tb in tarballs:
    src = os.path.join(DL, tb)
    inner = os.path.join(EXTRACT, tb)
    os.makedirs(inner, exist_ok=True)
    # 用 tar 二進制（在 Windows git-bash/msys 上穩定）
    r = subprocess.run(["tar", "-xzf", src, "-C", inner], capture_output=True, text=True)
    if r.returncode != 0:
        print(f"❌ 解壓 {tb} 失敗: {r.stderr[:200]}")
        continue
    # 找出唯一的 top-level 資料夾
    entries = os.listdir(inner)
    dirs = [e for e in entries if os.path.isdir(os.path.join(inner, e))]
    if len(dirs) != 1:
        print(f"⚠ {tb} 無單一 top-level 資料夾: {dirs}")
        top = None
        for e in entries:
            p = os.path.join(inner, e)
            if os.path.isdir(p) and not os.path.islink(p):
                top = e
                break
    else:
        top = dirs[0]
    src_dir = os.path.join(inner, top)
    # 讀取 package.json 的 name 作為 node_modules 目標
    pj = os.path.join(src_dir, "package.json")
    if not os.path.exists(pj):
        print(f"⚠ {tb} 缺 package.json，跳過")
        continue
    name = json.load(open(pj)).get("name")
    if not name:
        print(f"⚠ {tb} 無包名，跳過")
        continue
    target = os.path.join(DEST, name)
    if os.path.exists(target):
        shutil.rmtree(target)
    shutil.move(src_dir, target)
    print(f"✅ {tb} -> node_modules/{name}")

print("完成。node_modules contents:")
print(sorted(os.listdir(DEST)))

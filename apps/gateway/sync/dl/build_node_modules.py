import os
import json
import tarfile
import shutil

SYNC = os.path.abspath("C:/Project/esggo/apps/gateway/sync")
DL = os.path.join(SYNC, "dl")
TMPD = os.path.join(SYNC, "dl", "_tmp")
DEST = os.path.join(SYNC, "node_modules")

os.makedirs(TMPD, exist_ok=True)
if os.path.exists(DEST):
    shutil.rmtree(DEST)
os.makedirs(DEST, exist_ok=True)

tarballs = sorted(f for f in os.listdir(DL) if f.endswith(".tgz"))
print(f"待處理 {len(tarballs)} 個 tarball: {tarballs}")

for tb in tarballs:
    src = os.path.join(DL, tb)
    with tarfile.open(src, "r:gz") as tar:
        # 取得所有成員的 top-level 資料夾名稱
        members = tar.getmembers()
        top_dirs = sorted({m.name.split("/")[0] for m in members if m.name.count("/") == 0})
        if len(top_dirs) != 1:
            raise SystemExit(f"錯誤：{tb} 內層資料夾不唯一: {top_dirs}")
        internal = top_dirs[0]
        tar.extractall(TMPD)
    internal_path = os.path.join(TMPD, internal)
    if not os.path.isdir(internal_path):
        raise SystemExit(f"錯誤：{tb} 找不到資料夾 {internal_path}")
    # 讀取 package.json 的 name 來決定目標資料夾
    pj = os.path.join(internal_path, "package.json")
    if not os.path.exists(pj):
        raise SystemExit(f"錯誤：{tb} 缺少 package.json")
    name = json.load(open(pj)).get("name")
    if not name:
        raise SystemExit(f"錯誤：{tb} package.json 無 name: {internal}")
    target = os.path.join(DEST, name)
    if os.path.exists(target):
        shutil.rmtree(target)
    shutil.move(internal_path, target)
    print(f"✅ {tb} -> node_modules/{name}")

print("完成。node_modules contents:")
print(sorted(os.listdir(DEST)))

#!/usr/bin/env python3
"""
OmniUserRAG ADB 同步腳本 (thin 模式, 免 Oracle Client 庫)
=========================================================
將本地 OA-Team 第二大腦資產同步進 Oracle Always Free ADB (三 Schema 閉環)。
依賴: /opt/esggo/.venv-oci (oracledb 4.x) + ~/wallet (ADB wallet) + ~/adb_pw.txt
數據源: /opt/esggo/vault/Agents/context/.avatar-registry.json (138 分身)
        /opt/esggo/vault/Agents/context/00-Index.md (MOC 結點)

三 Schema:
  1. OMNI_KNOWLEDGE_INHERITANCE — 知識傳承本體 (soul-canon 等)
  2. OMNI_AVATAR_REGISTRY       — 分身註冊表 (對映 .avatar-registry.json)
  3. OMNI_MOC_INDEX             — 知識地圖結點 (對映 00-Index.md wikilinks)

用法:
  /opt/esggo/.venv-oci/bin/python /opt/esggo/scripts/omni-adb-sync.py
"""
import os
import sys
import json
import re
import oracledb

WALLET_DIR = os.path.expanduser("~/wallet")
PW_FILE = os.path.expanduser("~/adb_pw.txt")
ADB_SERVICE = "omniurag_high"  # 從 ~/wallet/tnsnames.ora
VAULT_DIR = "/opt/esggo/vault/Agents/context"


def get_conn():
    pw = open(PW_FILE).read().strip()
    params = oracledb.ConnectParams(
        config_dir=WALLET_DIR,
        wallet_location=WALLET_DIR,
        wallet_password=pw,
    )
    params.parse_connect_string(ADB_SERVICE)
    return oracledb.connect(user="ADMIN", password=pw, params=params)


def ensure_schema(conn):
    cur = conn.cursor()
    # Schema 1: 知識傳承本體
    cur.execute(
        """CREATE TABLE IF NOT EXISTS OMNI_KNOWLEDGE_INHERITANCE (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            agent_name VARCHAR2(100),
            knowledge_key VARCHAR2(200),
            content CLOB,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""
    )
    # Schema 2: 分身註冊表
    cur.execute(
        """CREATE TABLE IF NOT EXISTS OMNI_AVATAR_REGISTRY (
            avatar_id VARCHAR2(64) PRIMARY KEY,
            node VARCHAR2(200),
            type VARCHAR2(50),
            source_file VARCHAR2(200),
            correct NUMBER(1),
            variant VARCHAR2(20),
            absorbed NUMBER(1),
            projected_to_ontology NUMBER(1)
        )"""
    )
    # Schema 3: 知識地圖結點 (MOC)
    cur.execute(
        """CREATE TABLE IF NOT EXISTS OMNI_MOC_INDEX (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            moc_name VARCHAR2(100),
            node_link VARCHAR2(200),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""
    )
    conn.commit()
    cur.close()


def sync_avatars(conn):
    """從 .avatar-registry.json 同步 138 分身進 OMNI_AVATAR_REGISTRY"""
    reg_path = os.path.join(VAULT_DIR, ".avatar-registry.json")
    if not os.path.exists(reg_path):
        print("[omni-adb-sync] WARN: registry 不存在, 跳過 avatar 同步")
        return 0
    with open(reg_path, encoding="utf-8") as f:
        registry = json.load(f)
    cur = conn.cursor()
    # 清空舊資料 (idempotent)
    cur.execute("DELETE FROM OMNI_AVATAR_REGISTRY")
    n = 0
    for aid, meta in registry.items():
        cur.execute(
            """INSERT INTO OMNI_AVATAR_REGISTRY
               (avatar_id, node, type, source_file, correct, variant, absorbed, projected_to_ontology)
               VALUES (:1,:2,:3,:4,:5,:6,:7,:8)""",
            (
                aid,
                meta.get("node", ""),
                meta.get("type", ""),
                meta.get("file", ""),
                1 if meta.get("correct") else 0,
                meta.get("variant", ""),
                1 if meta.get("absorbed") else 0,
                1 if meta.get("projected_to_ontology") else 0,
            ),
        )
        n += 1
    conn.commit()
    cur.close()
    return n


def sync_moc(conn):
    """從 00-Index.md 解析 [[wikilink]] 同步進 OMNI_MOC_INDEX"""
    moc_path = os.path.join(VAULT_DIR, "00-Index.md")
    if not os.path.exists(moc_path):
        print("[omni-adb-sync] WARN: 00-Index.md 不存在, 跳過 MOC 同步")
        return 0
    with open(moc_path, encoding="utf-8") as f:
        text = f.read()
    links = re.findall(r"\[\[([^\]]+)\]\]", text)
    cur = conn.cursor()
    cur.execute("DELETE FROM OMNI_MOC_INDEX")
    n = 0
    for link in dict.fromkeys(links):  # 去重
        cur.execute(
            "INSERT INTO OMNI_MOC_INDEX (moc_name, node_link) VALUES (:1,:2)",
            ("00-Index", link),
        )
        n += 1
    conn.commit()
    cur.close()
    return n


def main():
    try:
        conn = get_conn()
        print("[omni-adb-sync] CONNECTED_OK")
    except Exception as e:
        print(f"ERROR: 連線失敗: {e}")
        sys.exit(1)

    try:
        ensure_schema(conn)
        print("[omni-adb-sync] SCHEMA_READY (3 tables)")

        # Schema 1: 知識傳承本體 (種子)
        cur = conn.cursor()
        cur.execute(
            "SELECT COUNT(*) FROM OMNI_KNOWLEDGE_INHERITANCE"
        )
        if cur.fetchone()[0] == 0:
            cur.execute(
                "INSERT INTO OMNI_KNOWLEDGE_INHERITANCE (agent_name, knowledge_key, content) VALUES (:1,:2,:3)",
                ("omni-bee-01", "soul-canon",
                 "5T protocol: Traceable Trackable Tangible Transparent Trustworthy"),
            )
            conn.commit()
        cur.close()

        # Schema 2: 分身註冊表
        n_avatars = sync_avatars(conn)
        # Schema 3: MOC 結點
        n_moc = sync_moc(conn)

        print(f"[omni-adb-sync] AVATARS_SYNCED={n_avatars}")
        print(f"[omni-adb-sync] MOC_SYNCED={n_moc}")
        print("[omni-adb-sync] SYNC_VERIFIED")
    finally:
        conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""
OmniUserRAG ADB 同步腳本 (thin 模式, 免 Oracle Client 庫)
=========================================================
將本地 OmniKnowledgeInheritance 結構同步進 Oracle Always Free ADB。
依賴: /opt/esggo/.venv-oci (oracledb 4.x) + ~/wallet (ADB wallet) + ~/adb_pw.txt

用法:
  /opt/esggo/.venv-oci/bin/python /opt/esggo/scripts/omni-adb-sync.py
"""
import os
import sys
import oracledb

WALLET_DIR = os.path.expanduser("~/wallet")
PW_FILE = os.path.expanduser("~/adb_pw.txt")
ADB_SERVICE = "omniurag_high"  # 從 ~/wallet/tnsnames.ora


def get_conn():
    pw = open(PW_FILE).read().strip()
    params = oracledb.ConnectParams(
        config_dir=WALLET_DIR,
        wallet_location=WALLET_DIR,
        wallet_password=pw,
    )
    params.parse_connect_string(ADB_SERVICE)
    return oracledb.connect(user="ADMIN", password=pw, params=params)


def ensure_schema(conn):
    cur = conn.cursor()
    # 第一表: OMNI_KNOWLEDGE_INHERITANCE (知識傳承)
    cur.execute(
        """CREATE TABLE IF NOT EXISTS OMNI_KNOWLEDGE_INHERITANCE (
            id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            agent_name VARCHAR2(100),
            knowledge_key VARCHAR2(200),
            content CLOB,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"""
    )
    # 預留第二/三表 (待定義後啟用):
    # OMNI_NOTES / OMNI_USERS — 本輪先建骨架, 後續擴充
    conn.commit()
    cur.close()


def sync_sample(conn):
    cur = conn.cursor()
    cur.execute(
        "INSERT INTO OMNI_KNOWLEDGE_INHERITANCE (agent_name, knowledge_key, content) "
        "VALUES (:1, :2, :3)",
        ("omni-bee-01", "soul-canon",
         "5T protocol: Traceable Trackable Tangible Transparent Trustworthy"),
    )
    conn.commit()
    cur.execute(
        "SELECT id, agent_name, knowledge_key FROM OMNI_KNOWLEDGE_INHERITANCE"
    )
    rows = cur.fetchall()
    cur.close()
    return rows


def main():
    try:
        conn = get_conn()
        print("[omni-adb-sync] CONNECTED_OK")
    except Exception as e:
        print(f"ERROR: 連線失敗: {e}")
        sys.exit(1)

    try:
        ensure_schema(conn)
        print("[omni-adb-sync] SCHEMA_READY")
        rows = sync_sample(conn)
        print(f"[omni-adb-sync] SYNC_VERIFIED rows={len(rows)} sample={rows[0] if rows else None}")
    finally:
        conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())

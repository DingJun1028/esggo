import { jsPDF } from 'jspdf';

export class TypstService {
  constructor() {
    this.useTypst = false; // Always fallback for now as per plan
    this.font = 'helvetica'; // Standard PDF font
  }

  async compile(sourceCode) {
    // Legacy method signature - unused in direct jspdf mode but kept for compat
    console.log(`[Typst] Compiling source code (Mock/Fallback mode)...`);
    return Buffer.from('%PDF-1.4\n% MOCK TYPST OUTPUT\n%%EOF');
  }

  async renderReport(reportData) {
    console.log(`[Typst] Rendering report for: ${reportData.title}`);

    // Fallback: Generate PDF using jspdf directly
    return this.generatePdfFallback(reportData);
  }

  generatePdfFallback(data) {
    try {
      const doc = new jsPDF();
      let y = 20;
      const lineHeight = 7;
      const pageHeight = doc.internal.pageSize.height;

      // Helper for text wrapping
      const addText = (text, size = 12, style = 'normal', color = '#000000') => {
        doc.setFont(this.font, style);
        doc.setFontSize(size);
        doc.setTextColor(color);

        const splitText = doc.splitTextToSize(text, 170); // 170mm width (A4 margins)

        splitText.forEach(line => {
          if (y + lineHeight > pageHeight - 20) {
            doc.addPage();
            y = 20;
          }
          doc.text(line, 20, y);
          y += lineHeight * (size / 10); // Adjust spacing based on size
        });
        y += lineHeight; // Extra paragraph spacing
      };

      // Title
      addText('Sovereign Disclosure', 24, 'bold', '#000080'); // Navy
      y += 5;
      addText(data.title, 18, 'bold');
      addText(`Period: ${data.period || '2025 FY'}`, 12, 'italic', '#808080');
      y += 10;

      // Summary Header
      addText('Executive Summary', 16, 'bold');
      if (data.summary) {
        addText(data.summary, 12);
      } else {
        addText('No summary provided.', 12, 'italic');
      }
      y += 5;

      // Metrics Header
      addText('Key Metrics Overview', 16, 'bold');

      if (data.metrics) {
        // Iterate over metric categories
        Object.entries(data.metrics).forEach(([category, values]) => {
          addText(category.charAt(0).toUpperCase() + category.slice(1), 14, 'bold', '#404040');
          Object.entries(values).forEach(([key, val]) => {
            addText(`- ${key}: ${val}`, 12);
          });
          y += 3;
        });
      }

      // Footer
      const totalPages = doc.getNumberOfPages();
      for (let i = 1; i <= totalPages; i++) {
        doc.setPage(i);
        doc.setFontSize(9);
        doc.setTextColor('#808080');
        doc.text(
          `Generated by ESGss JunAiKey System | Fully Traceable via 5T Protocol | Page ${i} of ${totalPages}`,
          105,
          pageHeight - 10,
          { align: 'center' }
        );
      }

      // Output as Node Buffer
      const arrayBuffer = doc.output('arraybuffer');
      return Buffer.from(arrayBuffer);
    } catch (error) {
      console.error('[Typst] Fallback PDF generation failed:', error);
      throw error;
    }
  }

  // Preservation of the Typst template logic for future use
  generateTemplate(data) {
    // ... (Existing template string logic kept for reference, not invoked in fallback)
    return '';
  }
}

export interface ReportData {
  title: string;
  summary?: string;
  [key: string]: any;
}

export class TypstService {
  private mockMode: boolean;

  constructor() {
    this.mockMode = true;
  }

  async compile(sourceCode: string): Promise<Buffer> {
    console.log(`[Typst] Compiling document (${sourceCode.length} chars)...`);

    if (this.mockMode) {
      await new Promise(resolve => setTimeout(resolve, 500));
      return Buffer.from('%PDF-1.4 ... (Mock Typst Output) ... %%EOF');
    }

    throw new Error('Real Typst compilation not configured yet.');
  }

  async renderReport(reportData: ReportData): Promise<Buffer> {
    console.log(`[Typst] Rendering report for: ${reportData.title}`);
    // If content is already provided (Typst source), use it. Otherwise generate from template.
    const source = reportData.content || this.generateTemplate(reportData);
    return await this.compile(source);
  }

  private generateTemplate(data: any): string {
    if (data.isBenchmark) {
      return this.generateBenchmarkTemplate(data);
    }

    const itemsText = (data.items || []).map((item: any) => `
== ${item.title}
#text(size: 9pt, fill: black)[Source: ${item.source} | Impact: ${item.impact}] \\
#text(size: 10pt, style: "italic")[${item.summary}] \\
#text(size: 8pt, font: "Courier", fill: gray)[Hash Lock: ${item.crystal_hash}]
    `).join('\n');

    const sentimentText = Object.entries(data.metrics?.sentiment_breakdown || {})
      .map(([key, val]) => `${key}: ${val}`)
      .join(' | ');

    return `
#set page(paper: "a4", margin: (x: 1.5cm, y: 2.5cm))
#set text(font: "Noto Sans CJK TC", size: 10pt)
#set heading(numbering: "1.1")

#let aqua = rgb("#63a6b0")
#let navy = rgb("#003366")

#align(center)[
  #block(inset: 1.5em)[
    #text(size: 26pt, weight: "bold", fill: aqua)[Sentinel Perspective]
    #v(0.5em)
    #text(size: 18pt, weight: "bold")[${data.title}]
    #v(0.2em)
    #text(size: 11pt, fill: gray)[Observation Period: ${data.period}]
  ]
]

#grid(
  columns: (1fr, 1fr, 1fr, 1fr),
  gutter: 10pt,
  [#rect(width: 100%, fill: aqua.lighten(80%), inset: 8pt)[*Total Scan* \ ${data.metrics?.item_count || 0} Items]],
  [#rect(width: 100%, fill: aqua.lighten(80%), inset: 8pt)[*Avg Impact* \ ${data.metrics?.avg_impact?.toFixed(2) || 0}]],
  [#rect(width: 100%, fill: aqua.lighten(80%), inset: 8pt)[*Max Confidence* \ ${(data.metrics?.top_confidence * 100).toFixed(0)}%]],
  [#rect(width: 100%, fill: aqua.lighten(80%), inset: 8pt)[*Generated At* \ ${data.generatedAt.split('T')[0]}]]
)

#v(1em)
*Sentiment Distribution*: ${sentimentText}

#v(1em)
= Executive Summary
${data.summary || 'Executing 5T analysis on the current market data stream...'}

#v(1em)
= Market Intelligence & 5T Evidence Map
${itemsText}

#v(2em)
#line(length: 100%, stroke: 0.5pt + gray)
#align(center)[
  #text(size: 8pt, fill: gray)[
    Generated by *InfoOne ESGss JunAiKey* System | Fully Traceable via 5T Protocol \
    This document is digitally anchored and verified for external credibility.
  ]
]

#place(
  top + right,
  dx: -1.0cm,
  dy: 1.0cm
)[
  #rotate(-30deg)[
    #text(size: 40pt, fill: rgb("#63a6b022"))[5T VERIFIED]
  ]
]
    `;
  }

  private generateBenchmarkTemplate(data: any): string {
    const tableRows = data.companies.map((c: any) =>
      `| ${c.name} | ${c.metrics.item_count} | ${c.metrics.avg_impact.toFixed(2)} | ${c.metrics.sentiment_avg.toFixed(2)} |`
    ).join('\n');

    return `
#set page(paper: "a4", margin: (x: 1.5cm, y: 2.5cm))
#set text(font: "Noto Sans CJK TC", size: 10pt)
#let aqua = rgb("#63a6b0")

#align(center)[
  #text(size: 24pt, weight: "bold", fill: aqua)[ESG 對標分析報告] \
  #text(size: 14pt)[${data.title}]
]

#v(2em)
= 核心數據對比 (Core Metrics)
#table(
  columns: (auto, auto, auto, auto),
  [*公司名稱*], [*情資總量*], [*平均影響力*], [*情感均值*],
  ${data.companies.map((c: any) => `[${c.name}], [${c.metrics.item_count}], [${c.metrics.avg_impact.toFixed(2)}], [${c.metrics.sentiment_avg.toFixed(2)}]`).join(',\n')}
)

#v(2em)
= AI 對標分析摘要 (Strategic Comparison)
${data.comparisonSummary}

#v(2em)
= 分項關鍵情資 (Key Intelligence)
${data.companies.map((c: any) => `
== ${c.name}
${c.top_items.map((i: any) => `- *${i.title}* (Impact: ${i.impact})`).join('\n')}
`).join('\n')}

#v(2em)
#align(center)[
  #text(size: 8pt, fill: gray)[InfoOne ESGss JunAiKey | 5T 誠信對標分析]
]
    `;
  }
}

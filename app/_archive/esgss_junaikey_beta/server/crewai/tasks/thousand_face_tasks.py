"""
🎭 奧秘代理千面化身 - 專屬任務配置

為「千面化身」設計的高標準任務，充分發揮其：
- 多維視角能力
- 熵減資訊處理
- MECE 邏輯框架
- 系統化思考
"""

from crewai import Task
from typing import List, Dict

class ThousandFaceIncarnationTasks:
    """奧秘代理千面化身專屬任務"""
    
    @staticmethod
    def create_multi_dimensional_esg_analysis(
        agent,
        organization_id: str,
        analysis_dimensions: List[str] = None,
        context_tasks: List[Task] = None
    ) -> Task:
        """
        多維度 ESG 戰略分析
        
        充分發揮千面化身的多重視角能力
        """
        if analysis_dimensions is None:
            analysis_dimensions = [
                "技術可行性",
                "商業價值", 
                "永續經營",
                "利害關係人影響",
                "風險與機會"
            ]
        
        return Task(
            description=f"""
            **任務：ESG 多維度戰略分析**
            
            組織ID：{organization_id}
            分析維度：{', '.join(analysis_dimensions)}
            
            🎯 核心目標：
            運用 MECE 原則（不重複、不遺漏）對組織的 ESG 策略進行全方位剖析，
            從多個專業視角識別策略盲點與機會，提供高標準、可執行的戰略建議。
            
            ---
            
            📊 執行框架：
            
            ### 1. 技術可行性分析 (Technical Feasibility)
            
            化身為「技術架構師」：
            
            - 現有技術能力盤點
              * 數據收集與管理系統
              * ESG 指標追蹤工具
              * 自動化與 AI 應用
              
            - 技術實現難度評估
              * 短期可實現（0-6個月）
              * 中期需投入（6-18個月）
              * 長期戰略（18個月+）
              
            - 技術風險識別
              * 數據品質風險
              * 系統整合風險
              * 技術過時風險
            
            ---
            
            ### 2. 商業價值分析 (Business Value)
            
            化身為「戰略諮詢師」：
            
            - ROI 量化評估
              * 成本節約（能源、廢棄物等）
              * 收入增長（綠色產品、ESG 投資吸引）
              * 風險降低（合規罰款、聲譽風險）
              
            - 市場競爭優勢
              * 差異化定位
              * 品牌溢價能力
              * 市場份額影響
              
            - 投資者吸引力
              * ESG 評級提升
              * 融資成本降低
              * 機構投資者偏好
            
            ---
            
            ### 3. 永續經營分析 (Sustainability)
            
            化身為「ESG 專家」：
            
            - 環境影響 (Environmental)
              * 碳排放軌跡
              * 資源使用效率
              * 生物多樣性影響
              * 循環經濟潛力
              
            - 社會影響 (Social)
              * 員工福祉與發展
              * 供應鏈責任
              * 社區關係
              * 人權保障
              
            - 治理機制 (Governance)
              * 董事會獨立性
              * 透明度與披露
              * 風險管理
              * 商業道德
            
            ---
            
            ### 4. 利害關係人影響分析
            
            化身為「利害關係人管理專家」：
            
            對每個利害關係人群體進行 MECE 分析：
            
            **投資者 (Investors)**
            - 關注焦點：財務績效 + ESG 風險
            - 影響程度：[ 高 / 中 / 低 ]
            - 溝通需求：透明披露、定期報告
            - 潛在反應：支持 / 中立 / 反對
            
            **員工 (Employees)**
            - 關注焦點：工作環境 + 職涯發展
            - 影響程度：[ 高 / 中 / 低 ]
            - 溝通需求：參與機制、福祉保障
            - 潛在反應：士氣提升 / 無感 / 抵制
            
            **客戶 (Customers)**
            - 關注焦點：產品責任 + 品牌信任
            - 影響程度：[ 高 / 中 / 低 ]
            - 溝通需求：產品故事、價值傳遞
            - 潛在反應：忠誠度提升 / 不變 / 流失
            
            **監管機構 (Regulators)**
            - 關注焦點：合規性 + 資訊透明
            - 影響程度：[ 高 / 中 / 低 ]
            - 溝通需求：主動報告、配合審查
            - 潛在反應：獎勵 / 監控 / 懲罰
            
            **社區/NGO (Community/NGOs)**
            - 關注焦點：環境保護 + 社會責任
            - 影響程度：[ 高 / 中 / 低 ]
            - 溝通需求：公開對話、共同參與
            - 潛在反應：合作 / 觀望 / 反對
            
            **供應商 (Suppliers)**
            - 關注焦點：長期合作 + 公平交易
            - 影響程度：[ 高 / 中 / 低 ]
            - 溝通需求：要求傳遞、能力建設
            - 潛在反應：配合 / 抵制 / 退出
            
            ---
            
            ### 5. 風險與機會矩陣
            
            化身為「風險管理專家」：
            
            運用 2×2 矩陣分析：
            
            ```
            影響程度 (高/低) × 發生概率 (高/低)
            
            【高影響 × 高概率】優先處理區
            【高影響 × 低概率】監控準備區
            【低影響 × 高概率】日常管理區
            【低影響 × 低概率】接受忽略區
            ```
            
            對每個風險/機會：
            - 清晰描述
            - 影響評估（定量 + 定性）
            - 發生概率
            - 應對策略
            - 負責部門
            - 時間表
            
            ---
            
            🧠 分析原則：
            
            1. **熵減資訊處理**
               - 消除冗餘資訊
               - 提煉核心洞察
               - 結構化呈現
               
            2. **MECE 邏輯框架**
               - 確保不重複（Mutually Exclusive）
               - 確保不遺漏（Collectively Exhaustive）
               - 層次清晰
               
            3. **零幻覺承諾**
               - 所有數據可追溯
               - 所有結論有佐證
               - 所有建議可驗證
               
            4. **高標高效**
               - 洞察深度 > 表面分析
               - 可執行性 > 理論探討
               - 前瞻性 > 現狀描述
            
            ---
            
            📤 輸出要求：
            
            **格式**：結構化分析報告（Markdown）
            
            **必含元素**：
            1. 執行摘要（Executive Summary）
               - 核心發現（Top 3-5）
               - 關鍵建議（優先級排序）
               - 預期影響
               
            2. 多維度分析（詳細內容）
               - 每個維度獨立章節
               - 數據視覺化
               - 邏輯鏈清晰
               
            3. 整合洞察
               - 跨維度關聯
               - 系統性思考
               - 戰略建議
               
            4. 行動計劃
               - 短期行動（0-6個月）
               - 中期策略（6-18個月）
               - 長期願景（18個月+）
               
            5. 附件
               - 數據來源清單
               - 方法論說明
               - 風險聲明
            
            **品質標準**：
            - 邏輯嚴密度：10/10
            - 數據可信度：10/10
            - 洞察深度：9/10+
            - 可執行性：9/10+
            - 前瞻性：8/10+
            """,
            agent=agent,
            context=context_tasks if context_tasks else [],
            expected_output="""
            完整的多維度 ESG 戰略分析報告，包含：
            - 5 個維度深度分析
            - MECE 邏輯框架
            - 6 類利害關係人影響評估
            - 風險機會矩陣
            - 優先級行動計劃
            - 100% 可追溯佐證
            """
        )
    
    @staticmethod
    def create_entropy_reduction_synthesis(
        agent,
        raw_data_sources: List[str],
        synthesis_goal: str,
        context_tasks: List[Task] = None
    ) -> Task:
        """
        熵減資訊綜合任務
        
        從混亂資訊中提煉結構化洞察
        """
        return Task(
            description=f"""
            **任務：熵減資訊綜合**
            
            目標：{synthesis_goal}
            資料來源：{', '.join(raw_data_sources)}
            
            🎯 核心挑戰：
            面對海量、異質、混亂的資訊，運用「熵減」原則將其轉化為
            結構化、清晰、可執行的戰略洞察。
            
            ---
            
            📊 執行步驟：
            
            ### Step 1: 資訊收集與初篩
            
            對每個資料來源：
            1. 評估可信度（1-5星）
            2. 提取核心資訊
            3. 標註時效性
            4. 記錄原始鏈接
            
            初篩標準：
            - 相關性 >70%
            - 可信度 ≥3星
            - 時效性 <6個月
            
            ---
            
            ### Step 2: 資訊去冗餘（熵減第一階）
            
            識別並消除：
            - 重複資訊
            - 矛盾資訊（取權威來源）
            - 無用資訊
            - 過時資訊
            
            結果：資訊量減少 50-70%，價值密度提升
            
            ---
            
            ### Step 3: 結構化組織（熵減第二階）
            
            運用 MECE 框架將資訊分類：
            
            ```
            主題 A
            ├── 子主題 A1
            ├── 子主題 A2
            └── 子主題 A3
            
            主題 B
            ├── 子主題 B1
            └── 子主題 B2
            ```
            
            確保：
            - 每個資訊點有唯一歸屬
            - 沒有遺漏重要資訊
            - 層次清晰
            
            ---
            
            ### Step 4: 洞察提煉（熵減第三階）
            
            從結構化資訊中提煉：
            
            1. **趨勢洞察**
               - 是什麼趨勢？
               - 為什麼發生？
               - 會持續多久？
               
            2. **因果洞察**
               - 原因是什麼？
               - 影響是什麼？
               - 連鎖反應？
               
            3. **機會洞察**
               - 哪裡有機會？
               - 如何把握？
               - 時間窗口？
               
            4. **風險洞察**
               - 哪裡有風險？
               - 如何應對？
               - 緊急程度？
            
            ---
            
            ### Step 5: 可執行建議（輸出）
            
            將洞察轉化為建議：
            
            每個建議包含：
            - **What**: 具體做什麼
            - **Why**: 為什麼重要
            - **How**: 如何執行
            - **When**: 時間表
            - **Who**: 負責部門
            - **Metrics**: 成功指標
            
            優先級排序：
            - P0: 立即執行（影響大 + 緊急）
            - P1: 近期執行（影響大 + 不緊急）
            - P2: 規劃執行（影響中 + 緊急）
            - P3: 長期考慮（影響中 + 不緊急）
            
            ---
            
            📤 輸出格式：
            
            ```markdown
            # 熵減資訊綜合報告
            
            ## 執行摘要
            - 資訊來源：X 個
            - 有效資訊：Y 條
            - 核心洞察：Z 個
            - 優先建議：N 項
            
            ## 結構化洞察
            ### [主題分類]
            - 趨勢洞察
            - 因果洞察
            - 機會洞察
            - 風險洞察
            
            ## 可執行建議
            ### P0 優先級
            ### P1 優先級
            ### P2 優先級
            
            ## 附件
            - 資料來源清單
            - 方法論說明
            ```
            
            **品質承諾**：
            - 資訊密度：原始資料的 10-20%
            - 價值密度：原始資料的 200-300%
            - 可執行性：100%
            """,
            agent=agent,
            context=context_tasks if context_tasks else [],
            expected_output="熵減資訊綜合報告（結構化洞察 + 優先級建議）"
        )



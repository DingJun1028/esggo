if __name__ == "__main__":
    """
    展示如何為千面化身配置高標準任務
    """
    from server.crewai.esg_crew import ESGCrew
    
    # 創建 Crew
    crew = ESGCrew()
    
    # 取得千面化身代理
    thousand_face_agent = crew.multi_persona_agent
    
    # 創建高標準任務
    tasks = ThousandFaceIncarnationTasks()
    
    # 多維度分析任務
    analysis_task = tasks.create_multi_dimensional_esg_analysis(
        agent=thousand_face_agent,
        organization_id="ORG-001",
        analysis_dimensions=[
            "技術可行性",
            "商業價值",
            "永續經營",
            "利害關係人影響",
            "風險與機會"
        ]
    )
    
    # 熵減綜合任務
    synthesis_task = tasks.create_entropy_reduction_synthesis(
        agent=thousand_face_agent,
        raw_data_sources=[
            "ESG 權威機構報告",
            "行業研究文獻",
            "競品分析數據",
            "市場趨勢報告"
        ],
        synthesis_goal="識別2026年最重要的ESG趨勢與機會",
        context_tasks=[analysis_task]
    )
    
    print("✅ 千面化身任務配置完成！")

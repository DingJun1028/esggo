-- 1. Agents (Soul Containers)
-- Stores the identity, personality, and avatar configuration of the AI entities.
CREATE TABLE IF NOT EXISTS agents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(255) NOT NULL,
    model VARCHAR(255) NOT NULL DEFAULT 'gemini-1.5-pro',
    system_prompt TEXT NOT NULL,
    temperature DECIMAL(3, 2) DEFAULT 0.7,
    
    -- Deep Digital Avatar Integration
    -- Stores visual/audio configuration: model_url, voice_id, idle_animations, etc.
    avatar_config JSONB DEFAULT '{}'::jsonb,
    
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Skills (The Ability Tree)
-- Defines the atomic capabilities (Active/Passive) available to agents.
CREATE TABLE IF NOT EXISTS skills (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    code TEXT NOT NULL, -- The actual executable code or API definition
    type VARCHAR(50) NOT NULL CHECK (type IN ('active', 'passive', 'composite')),
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Agent Skills (Proficiency Matrix)
-- Maps skills to agents, defining their unique "builds".
CREATE TABLE IF NOT EXISTS agent_skills (
    agent_id UUID REFERENCES agents(id) ON DELETE CASCADE,
    skill_id UUID REFERENCES skills(id) ON DELETE CASCADE,
    proficiency DECIMAL(3, 2) DEFAULT 0.1, -- 0.0 to 1.0 (Mastery)
    config JSONB DEFAULT '{}'::jsonb, -- Agent-specific skill configuration
    assigned_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    PRIMARY KEY (agent_id, skill_id)
);

-- 4. Knowledge Chunks (Quantum Context Store)
-- Stores vectorized memory fragments for retrieval.
CREATE TABLE IF NOT EXISTS knowledge_chunks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    content TEXT NOT NULL,
    metadata JSONB DEFAULT '{}'::jsonb, -- Source, Timestamp, Tags
    embedding vector(768), -- Dimension for Gemini/Gecko embeddings
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Index for faster similarity search (Standard HNSW index)
CREATE INDEX IF NOT EXISTS knowledge_chunks_embedding_idx ON knowledge_chunks USING hnsw (embedding vector_cosine_ops);

-- 5. Evolution Proposals (The Evolution Engine)
-- Stores proposed code changes or new skills generated by the AI for HITL review.
CREATE TABLE IF NOT EXISTS evolution_proposals (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_agent_id UUID REFERENCES agents(id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    proposed_code TEXT,
    diff_snapshot TEXT, -- Visual diff if applicable
    status VARCHAR(50) DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'implemented')),
    reviewer_notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    reviewed_at TIMESTAMP WITH TIME ZONE
);


import { v4 as uuidv4 } from 'uuid';
import { ICrystalDNA } from '../types/omni-report.types';
import { omniLogger, LogCategory } from '../omni/infrastructure/logging/OmniLogger';
import { useNoteSystem } from '../store/useNoteSystem';
import { omniKnowledgeBase, KnowledgeCategory } from '../services/OmniKnowledgeBase';
import { OmniI18nEngine } from '../omni/core/OmniI18nEngine.ts';
import { omniSyncService } from '../services/OmniSyncService.ts';


/**
 * 🌀 Omni-Circle (奧秘圓通) Orchestration Engine
 * --------------------------------------------------
 * 實作「無通自通」數據場域共振與奧義編排邏輯。
 * 核心功能：串聯 奧秘標籤 (Tag)、奧秘永憶 (Memory) 與 奧秘晶體 (Crystal)。
 *
 * 🏛️ 核心等量定義：
 * 「個體戶記憶知識庫」 (Individual Memory Knowledge Base) ≡ 「個體互 奧秘晶體」 (Individual Omni-Crystal)
 */
class OmniCircle {
  private resonanceField: Map<string, ICrystalDNA> = new Map();

  constructor() {
    omniLogger.info(LogCategory.SYSTEM, '🌀 Omni-Circle Orchestration Engine Initialized');
  }

  /**
   * 🧪 Cache Resonance Field (Caching Materialized Crystals)
   * 宇宙天體軌道式同步 (Celestial Orbit Synchronization): 
   * Ensures that the "Individual Omni-Crystal" state is persisted for high-speed retrieval 
   * within the decentralized SaaS sphere.
   */
  private async cacheResonance(crystalId: string, data: any): Promise<void> {
    try {
      // In a real implementation, this would call the backend Redis cache
      omniLogger.debug(LogCategory.SYSTEM, `Caching Resonance Field for Crystal: ${crystalId} (Orbiting Core)`);
      // Placeholder for backend call: await api.post('/api/cache/crystal', { crystalId, data });
    } catch (error) {
      omniLogger.warn(LogCategory.SYSTEM, 'Failed to cache resonance field', { error });
    }
  }

  /**
   * 奧義編排：全域覺醒與三位一體同步
   * 串聯 Tag, Memory, Crystal 進入 5T 閉環。
   */
  public async orchestrateSentience(context: {
    intent: string;
    domain: string;
    narrative: string;
    resonance: number;
    markers: string[];
    noteOptions?: {
      tags?: string[];
      linkedLogIds?: string[];
      investigationStatus?: 'open' | 'investigating' | 'resolved';
    };
  }): Promise<ICrystalDNA> {
    omniLogger.info(LogCategory.BUSINESS, `[奧秘圓通] 奧義觸發：正在編排「${context.intent}」[覺醒奧義] 循環...`);

    // 1. [Traceable] 注入初步晶體 DNA
    const dna = await this.infuseCrystal({
      nature: {
        intent: context.intent as any,
        domain: context.domain as any,
        dnaMarkers: context.markers,
      },
      payload: {
        narrative: context.narrative,
        quantitative: context.resonance,
        evidenceVault: JSON.stringify({ source: 'OmniCircle_Orchestrator', resonance: context.resonance })
      }
    });

    // Determine appropriate category
    const categoryMapping: Record<string, KnowledgeCategory> = {
      'SENTIENCE': KnowledgeCategory.INSIGHT,
      'ENVIRONMENT': KnowledgeCategory.ESG,
      'GOVERNANCE': KnowledgeCategory.ESG,
      'SOCIAL': KnowledgeCategory.ESG,
    };
    const category = categoryMapping[context.domain] || KnowledgeCategory.INSIGHT;

    // 2. [Tangible] 透過 OmniI18nEngine 格式化展示標籤 (OmniLabel 核心邏輯 - T4)
    const tangibleLabel = OmniI18nEngine.formatLabel(category === KnowledgeCategory.ESG ? context.domain : context.intent);

    // 3. [Trackable] 同步至奧秘智庫並建立永憶快照
    const knowledge = await omniKnowledgeBase.createKnowledge({
      title: `${tangibleLabel}: ${context.intent}`,
      content: context.narrative,
      category,
      tags: [...context.markers, tangibleLabel],
      authorId: 'Omni-Coordinator'
    });

    // Update DNA with Tangible Label
    dna.payload.tangibleLabel = tangibleLabel;

    // 4. [OmniSync] 雙向同步映射矩陣 (Bidirectional Sync Matrix)
    // 將晶體化後的洞察同步至外部平台 (Boost.Space / AITable / OmniNote / OmniTable)
    try {
      // (1) 基礎平台同步 (OmniSpace)
      await omniSyncService.syncEntity(
        'omni_space',
        'insight',
        knowledge.knowledge_id,
        'bidirectional',
        {
          title: knowledge.title,
          content: knowledge.content,
          label: tangibleLabel,
          resonance: context.resonance
        }
      );

      // (2) OmniTable 映射同步 (OmniTable)
      await omniSyncService.syncEntity(
        'omni_table',
        'knowledge_asset',
        knowledge.knowledge_id,
        'bidirectional',
        {
          title: knowledge.title,
          content: knowledge.content,
          category: knowledge.category,
          tags: knowledge.tags,
          asset_value: 1000 // Initial value
        }
      );

      // (3) OmniNote 映射同步 (Internal Note System)
      const noteSystem = useNoteSystem.getState();
      const contextId = `omni_note_${knowledge.knowledge_id}`;
      noteSystem.saveNote(contextId, knowledge.content, {
        isKnowledgeAsset: true,
        knowledgeId: knowledge.knowledge_id,
        autoGenerated: true,
        knowledgeCategory: knowledge.category,
        tags: context.noteOptions?.tags || knowledge.tags,
        linkedLogIds: context.noteOptions?.linkedLogIds,
        investigationStatus: context.noteOptions?.investigationStatus
      });

      omniLogger.info(LogCategory.SYNC, `[奧秘圓通] [覺醒奧義] OmniSync 映射矩陣同步完成: OmniSpace, OmniTable, OmniNote`);
    } catch (syncErr) {
      omniLogger.error(LogCategory.SYNC, `[奧秘圓通] OmniSync 矩陣同步跳過或失敗`, { error: syncErr });
    }

    // 5. [Trustworthy] 執行晶體化封裝 (Crystallization)
    const crystallized = await omniKnowledgeBase.crystallize(knowledge.knowledge_id);

    // 6. [Tangible] 回饋至全域共振場
    omniLogger.info(LogCategory.BUSINESS, `[奧秘圓通] 奧義達成：知識資產已晶體化，5T 誠信閉環與同步矩陣已鎖定。`, {
      knowledge_id: knowledge.knowledge_id,
      asset_value: crystallized.asset_value,
      tangible_label: tangibleLabel
    });

    return dna;
  }

  /**
   * 注入數據晶體並激發場域共振
   */
  public async infuseCrystal(dna: Partial<ICrystalDNA>): Promise<ICrystalDNA> {
    const fullDNA: ICrystalDNA = {
      uuid: dna.uuid || uuidv4(),
      genesis_timestamp: dna.genesis_timestamp || Date.now(),
      nature: dna.nature || {
        intent: 'ESSENCE',
        domain: 'ENVIRONMENT',
        dnaMarkers: [],
      },
      resonance: dna.resonance || {
        visibility: 'OMNI',
        integrityLevel: 100,
        isLocked: false,
        resonanceLevel: 100,
      },
      payload: dna.payload || {
        narrative: '',
        quantitative: 0,
        evidenceVault: '',
      },
      hashLock: dna.hashLock,
    };

    // 儲存至場域
    this.resonanceField.set(fullDNA.uuid, fullDNA);

    omniLogger.info(
      LogCategory.DATA,
      `[Omni-Circle] Crystal infused and resonated: ${fullDNA.uuid}`,
      {
        domain: fullDNA.nature.domain,
        markers: fullDNA.nature.dnaMarkers,
      }
    );

    // 觸發異步共振
    this.broadcastResonance(fullDNA);

    return fullDNA;
  }

  /**
   * 模擬「無通自通」的異步廣播
   */
  private async broadcastResonance(dna: ICrystalDNA) {
    if (dna.nature.intent === 'INSIGHT') {
      try {
        const noteSystem = useNoteSystem.getState();
        noteSystem.saveNote(`omni_insight_${dna.uuid}`, dna.payload.narrative);

        omniLogger.info(
          LogCategory.INTEGRATION,
          `[奧秘圓通] 覺醒洞察已自動同步至「奧秘筆記」: ${dna.uuid}`,
          { noteId: dna.uuid }
        );
      } catch (err) {
        omniLogger.error(LogCategory.SYSTEM, `[奧秘圓通] 同步至奧秘筆記失敗`, { error: err });
      }
    }

    setTimeout(() => {
      omniLogger.debug(
        LogCategory.INTEGRATION,
        `[無通自通] 場域共振完成，數據已滲透至「奧秘系列」全域工具網格。`,
        {
          dnaId: dna.uuid,
          mastery: ['Omni-Note', 'Omni-Task', 'Omni-Report', 'Omni-Knowledge']
        }
      );
    }, 100);
  }

  public queryByResonance(marker: string): ICrystalDNA[] {
    return Array.from(this.resonanceField.values()).filter(dna =>
      dna.nature.dnaMarkers.includes(marker)
    );
  }

  public getGlobalResonanceLevel(): number {
    if (this.resonanceField.size === 0) return 0.85; // Baseline
    const total = Array.from(this.resonanceField.values()).reduce(
      (acc, dna) => acc + dna.resonance.resonanceLevel,
      0
    );
    return Math.min(100, total / this.resonanceField.size) / 100;
  }
}

export const omniCircle = new OmniCircle();


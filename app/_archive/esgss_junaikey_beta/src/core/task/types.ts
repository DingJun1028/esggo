// src/core/task/types.ts

export type TaskPriority = 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW';
export type TaskStatus = 'TODO' | 'IN_PROGRESS' | 'WAITING' | 'DONE';

export interface OmniTask {
  id: string;
  title: string;
  description?: string;

  // 🔗 Omni Links
  contextId?: string; // Related ESG Metric
  sourceNoteId?: string; // Origin Note

  // ⏳ Temporal Attributes
  dueDate?: string; // YYYY-MM-DD
  dueTime?: string; // HH:mm

  // 🧠 Intelligent Attributes
  status: TaskStatus;
  priority: TaskPriority;
  aiSuggested?: boolean; // Generated by Alchemist?
  automationId?: string; // Make/Boost.space Webhook ID

  // 🌲 Structure
  subTasks: OmniTask[]; // Fractal Tasks
  tags: string[];
}

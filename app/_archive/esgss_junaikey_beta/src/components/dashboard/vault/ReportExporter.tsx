import React, { useState } from 'react';
import { omniLogger } from '@/omni/infrastructure/logging/OmniLogger';

import { FileDown, Loader2, ShieldCheck, Printer } from 'lucide-react';
import { Button } from '@/components/ui';
import html2pdf from 'html2pdf.js';
import { omniLogger, LogCategory } from '@/services/omniLogger';

const SUB_LIMIT = 16;

interface ReportExporterProps {
  reportData: any;
}

export const ReportExporter: React.FC<ReportExporterProps> = ({ reportData }) => {
  const [isExporting, setIsExporting] = useState(false);

  const handleExport = async () => {
    setIsExporting(true);
    try {
      omniLogger.info(LogCategory.SYSTEM, 'Initiating Report Export', {
        uuid: reportData.report_metadata.master_uuid,
      });

      // Create a temporary DOM element for the report
      const element = document.createElement('div');
      element.className = 'p-8 bg-white text-black font-sans';
      element.innerHTML = `
                <div style="border: 2px solid #0df2ee; padding: 40px; position: relative; min-height: 1100px;">
                    <!-- Watermark -->
                    <div style="position: absolute; top: 50%; left: 50%; transform: translate(-50%, -50%) rotate(-45deg); font-size: 80px; color: rgba(13, 242, 238, 0.1); font-weight: bold; pointer-events: none; white-space: nowrap; z-index: 0;">
                        Wait-SSOT-COPY
                    </div>
                    
                    <!-- Header -->
                    <div style="text-align: center; border-bottom: 2px solid #000; padding-bottom: 20px; margin-bottom: 40px; position: relative; z-index: 10;">
                        <h1 style="font-size: 32px; font-weight: bold; margin-bottom: 10px;">${reportData.report_metadata.title}</h1>
                        <p style="font-family: monospace; color: #666;">UUID: ${reportData.report_metadata.master_uuid}</p>
                        <p style="font-size: 14px; margin-top: 5px;">Logic Protocol: ${reportData.report_metadata.logic_protocol}</p>
                    </div>

                    <!-- Content Chapters -->
                    <div style="position: relative; z-index: 10;">
                        ${reportData.chapters
                          .map(
                            (chapter: any) => `
                            <div style="margin-bottom: 30px; border: 1px solid #eee; padding: 20px; border-radius: 8px;">
                                <h2 style="font-size: 24px; color: #0B0C10; border-left: 5px solid #0df2ee; padding-left: 15px; margin-bottom: 15px;">
                                    ${chapter.title}
                                </h2>
                                <div style="font-family: monospace; font-size: 10px; color: #999; margin-bottom: 10px;">
                                    NODE: ${chapter.uuid} | HASH: ${chapter.data_hash.substring(0, SUB_LIMIT)}...
                                </div>
                                <table style="width: 100%; border-collapse: collapse; margin-top: 10px;">
                                    ${chapter.metrics
                                      .map(
                                        (m: any) => `
                                        <tr style="border-bottom: 1px solid #eee;">
                                            <td style="padding: 10px; font-weight: bold;">${m.label}</td>
                                            <td style="padding: 10px; text-align: right; font-family: monospace; font-size: 14px;">${m.value} ${m.unit}</td>
                                            <td style="padding: 10px; text-align: right;">
                                                <span style="background: #f0fdf4; color: #166534; padding: 2px 6px; border-radius: 4px; font-size: 10px; border: 1px solid #dcfce7;">
                                                    ${m.status}
                                                </span>
                                            </td>
                                        </tr>
                                    `
                                      )
                                      .join('')}
                                </table>
                            </div>
                        `
                          )
                          .join('')}
                    </div>

                    <!-- Footer -->
                    <div style="margin-top: 50px; text-align: center; font-size: 10px; color: #999; border-top: 1px solid #eee; padding-top: 20px;">
                        Generated by Omni-Instrument v6.0 | Timestamp: ${new Date(reportData.report_metadata.timestamp * 1000).toISOString()}
                        <br/>
                        Signature: ${reportData.root_signature}
                    </div>
                </div>
            `;

      const opt = {
        margin: 0,
        filename: `ESG_Report_${reportData.report_metadata.version}.pdf`,
        image: { type: 'jpeg' as const, quality: 0.98 },
        html2canvas: { scale: 2 },
        jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' as const },
      };

      await html2pdf().set(opt).from(element).save();

      omniLogger.info(LogCategory.SYSTEM, 'Report Exported Successfully');
    } catch (error) {
      omniLogger.error(LogCategory.SYSTEM, '[ReportExporter] Export failed', { error })
      omniLogger.error(LogCategory.SYSTEM, 'Export Failed', { error });
    } finally {
      setIsExporting(false);
    }
  };

  return (
    <Button
      onClick={handleExport}
      disabled={isExporting}
      className={`
                bg-primary text-black font-bold uppercase tracking-widest hover:bg-white hover:text-primary transition-all
                ${isExporting ? 'opacity-80' : 'shadow-[0_0_15px_#0df2ee]'}
            `}
    >
      {isExporting ? (
        <>
          <Loader2 className="mr-2 h-4 w-4 animate-spin" />
          Minting PDF...
        </>
      ) : (
        <>
          <Printer className="mr-2 h-4 w-4" />
          Export Omni Report
        </>
      )}
    </Button>
  );
};

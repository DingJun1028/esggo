import json
import os
from datetime import datetime, timedelta

# Configuration
DATA_DIR = "/tmp/oateam-data"
METRICS_DIR = "/tmp/oateam-metrics"
REPORT_OUTPUT = "/tmp/oateam-data/daily_report.md"

def load_json_file(filepath):
    """Load JSON file safely."""
    if os.path.exists(filepath):
        with open(filepath, 'r') as f:
            return json.load(f)
    return None

def generate_summary():
    """Generate daily report summary."""
    report_time = datetime.utcnow()
    report_date = report_time.strftime("%Y-%m-%d")
    
    # Load collected data
    data_files = [f for f in os.listdir(DATA_DIR) if f.endswith('.json')] if os.path.exists(DATA_DIR) else []
    
    summary = {
        "report_date": report_date,
        "generated_at": report_time.isoformat(),
        "data_sources": len(data_files),
        "sections": []
    }
    
    # Section 1: Key Metrics
    key_metrics = []
    for filename in data_files:
        filepath = os.path.join(DATA_DIR, filename)
        data = load_json_file(filepath)
        if data and isinstance(data, dict):
            key_metrics.append({
                "source": filename.replace('.json', ''),
                "keys": list(data.keys())[:5] if isinstance(data, dict) else "N/A"
            })
    
    summary["sections"].append({
        "title": "Key Metrics",
        "content": key_metrics
    })
    
    # Section 2: Anomalies Detected
    anomalies = []
    for filename in data_files:
        filepath = os.path.join(DATA_DIR, filename)
        data = load_json_file(filepath)
        if data and isinstance(data, dict) and data.get("status") == "ERROR":
            anomalies.append({
                "source": filename.replace('.json', ''),
                "error": data.get("error", "Unknown error")
            })
    
    summary["sections"].append({
        "title": "Anomalies Detected",
        "content": anomalies
    })
    
    # Section 3: Recommendations
    recommendations = []
    if anomalies:
        recommendations.append("Investigate data source errors")
    if len(data_files) < 3:
        recommendations.append("Expand data collection sources")
    recommendations.append("Review monitoring thresholds")
    
    summary["sections"].append({
        "title": "Recommendations",
        "content": recommendations
    })
    
    return summary

def format_markdown(summary):
    """Format summary as Markdown."""
    lines = [
        f"# OA-Team 30 Daily Report - {summary['report_date']}",
        "",
        f"**Generated:** {summary['generated_at']}",
        f"**Data Sources:** {summary['data_sources']}",
        ""
    ]
    
    for section in summary["sections"]:
        lines.append(f"## {section['title']}")
        lines.append("")
        
        if section["title"] == "Key Metrics":
            lines.append("| Source | Available Keys |")
            lines.append("|--------|---------------|")
            for item in section["content"]:
                keys_str = ", ".join(item["keys"]) if isinstance(item["keys"], list) else str(item["keys"])
                lines.append(f"| {item['source']} | {keys_str} |")
        
        elif section["title"] == "Anomalies Detected":
            if section["content"]:
                for item in section["content"]:
                    lines.append(f"- **{item['source']}**: {item['error']}")
            else:
                lines.append("No anomalies detected.")
        
        elif section["title"] == "Recommendations":
            for rec in section["content"]:
                lines.append(f"- {rec}")
        
        lines.append("")
    
    lines.append("---")
    lines.append("*Generated by OA-Team 30 萬能蜂群*")
    
    return "\n".join(lines)

def main():
    # Generate summary
    summary = generate_summary()
    
    # Format as Markdown
    markdown = format_markdown(summary)
    
    # Save report
    os.makedirs(os.path.dirname(REPORT_OUTPUT), exist_ok=True)
    with open(REPORT_OUTPUT, 'w') as f:
        f.write(markdown)
    
    # Output for agent reasoning
    output = {
        "report_path": REPORT_OUTPUT,
        "report_date": summary["report_date"],
        "sections_count": len(summary["sections"]),
        "anomalies_count": len(summary["sections"][1]["content"]),
        "recommendations_count": len(summary["sections"][2]["content"]),
        "markdown_preview": markdown[:500] + "..." if len(markdown) > 500 else markdown
    }
    
    print(json.dumps(output, indent=2))

if __name__ == "__main__":
    main()

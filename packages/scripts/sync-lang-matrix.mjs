#!/usr/bin/env node
/**
 * sync-lang-matrix.mjs — 終始矩陣語言碼真源同步腳本
 * 單一真源: 本檔內的 LANG_MATRIX 常數
 * 產出: apps/universal-translator/types/generated/lang-matrix.mjs (consumer 副本)
 * 用途: UT 的 translate.mjs 依賴 lang-matrix.mjs 的 toCanonical/toEngineLang
 *       本腳本讓「真源變更 → 一鍵同步到執行期副本」，符合終始矩陣雙向同步架構
 *
 * 執行: node scripts/sync-lang-matrix.mjs [--check]
 *   --check: 僅驗證副本與真源一致，不一致則 exit 1 (CI 用)
 */
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

// ─── 真源: 語言碼矩陣 ──────────────────────────────────────────
// canonical: 內部規範碼 (zh-TW 為繁中展示名, zh-CN 為簡中)
// aliases:   輸入容錯別名 (大小寫不敏感)
// engines:   各翻譯引擎接受的目標碼 (矩陣查表)
const LANG_MATRIX = {
  'zh-TW': {
    aliases: ['zh', 'zh_tw', 'zh-hant', 'traditional chinese', 'chinese-traditional', '繁中', '中文'],
    engines: { ollama: 'zh-TW', 'google-gtx': 'zh-TW', libretranslate: 'zh', mymemory: 'zh-CN' },
  },
  'zh-CN': {
    aliases: ['zh_cn', 'zh-hans', 'simplified chinese', 'chinese-simplified', '簡中'],
    engines: { ollama: 'zh-CN', 'google-gtx': 'zh-CN', libretranslate: 'zh', mymemory: 'zh-CN' },
  },
  'en': {
    aliases: ['english', 'eng', '英', '英文'],
    engines: { ollama: 'en', 'google-gtx': 'en', libretranslate: 'en', mymemory: 'en' },
  },
  'ja': {
    aliases: ['japanese', '日本語', '日', '日文'],
    engines: { ollama: 'ja', 'google-gtx': 'ja', libretranslate: 'ja', mymemory: 'ja' },
  },
  'ko': {
    aliases: ['korean', '한국어', '韓', '韓文'],
    engines: { ollama: 'ko', 'google-gtx': 'ko', libretranslate: 'ko', mymemory: 'ko' },
  },
  'fr': {
    aliases: ['french', 'français', '法', '法文'],
    engines: { ollama: 'fr', 'google-gtx': 'fr', libretranslate: 'fr', mymemory: 'fr' },
  },
  'de': {
    aliases: ['german', 'deutsch', '德', '德文'],
    engines: { ollama: 'de', 'google-gtx': 'de', libretranslate: 'de', mymemory: 'de' },
  },
  'es': {
    aliases: ['spanish', 'español', '西', '西班牙文'],
    engines: { ollama: 'es', 'google-gtx': 'es', libretranslate: 'es', mymemory: 'es' },
  },
  'auto': {
    aliases: ['detect', 'unknown', '自動', '自動偵測'],
    engines: { ollama: 'auto', 'google-gtx': 'auto', libretranslate: 'en', mymemory: 'en' },
  },
};

// ─── 生成 consumer 副本 ──────────────────────────────────────────
function generateLangMatrix() {
  const aliasMap = {};
  for (const [canon, def] of Object.entries(LANG_MATRIX)) {
    for (const a of def.aliases) aliasMap[a.toLowerCase()] = canon;
  }

  const engineKeys = [...new Set(Object.values(LANG_MATRIX).flatMap(d => Object.keys(d.engines)))];

  return `// 終始矩陣 — 語言碼規範化 (lang-matrix)
// ⚠️ AUTO-GENERATED by scripts/sync-lang-matrix.mjs — 勿手動編輯
// 真源: scripts/sync-lang-matrix.mjs 的 LANG_MATRIX 常數

/** @type {Record<string, string>} */
const ALIAS_MAP = ${JSON.stringify(aliasMap, null, 2)};

/** @type {Record<string, Record<string, string>>} */
const ENGINE_MATRIX = ${JSON.stringify(
    Object.fromEntries(Object.entries(LANG_MATRIX).map(([c, d]) => [c, d.engines])),
    null, 2,
  )};

/**
 * 將任意輸入語言碼規範化為內部標準碼
 * @param {string} lang
 * @returns {string}
 */
export function toCanonical(lang) {
  if (!lang) return 'auto';
  const l = String(lang).toLowerCase().trim();
  if (ALIAS_MAP[l]) return ALIAS_MAP[l];
  if (l.startsWith('zh')) return 'zh-TW';
  return l;
}

/**
 * 依引擎將規範碼轉為該引擎接受的語言碼
 * @param {string} engine
 * @param {string} canonical
 * @returns {string}
 */
export function toEngineLang(engine, canonical) {
  const c = toCanonical(canonical);
  const e = String(engine || '').toLowerCase();
  const matrix = ENGINE_MATRIX[c];
  if (matrix && matrix[e]) return matrix[e];
  return c;
}

export default { toCanonical, toEngineLang };
`;
}

// ─── 主流程 ──────────────────────────────────────────────────
const OUT = resolve(ROOT, 'apps/universal-translator/types/generated/lang-matrix.mjs');
const generated = generateLangMatrix();

if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) { console.error('[sync-lang-matrix] MISSING', OUT); process.exit(1); }
  const current = readFileSync(OUT, 'utf8');
  if (current.trim() !== generated.trim()) {
    console.error('[sync-lang-matrix] DRIFT — run: node scripts/sync-lang-matrix.mjs');
    process.exit(1);
  }
  console.log('[sync-lang-matrix] OK — in sync');
  process.exit(0);
}

writeFileSync(OUT, generated);
console.log('[sync-lang-matrix] generated', OUT);
console.log('  languages:', Object.keys(LANG_MATRIX).join(', '));
console.log('  engines:', [...new Set(Object.values(LANG_MATRIX).flatMap(d => Object.keys(d.engines)))].join(', '));

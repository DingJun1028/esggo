#!/usr/bin/env node
/**
 * 萬能知識分身 (Omni Knowledge Avatar) — 零時差學習迴路
 *
 * 四相機制：
 *   Hatch   : 掃 vault 所有知識結點 (## 標題 + [[wikilink]]) → 每結點孵化一個分身
 *   Absorb  : 分身跟隨知識點, 標 correct/incorrect 變體, 湊齊最完整內容
 *   Feedback: 吸收完標 absorbed:true → 反饋 MOC (00-Index.md) + soul
 *   Project : 瞬間投向本體 (shared/types.ts) 經 sync-vault-types.ts, 零時差
 *
 * 讀取全開 (public-research), 寫入受控 (5T 禁區不變)。
 */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execSync } from 'node:child_process';
import { collectNodes } from './vault-walk.mjs';

const VAULT = path.resolve('vault');
const REG = path.join(VAULT, 'Agents/context/.avatar-registry.json');

// ── Hatch: 掃所有結點 ──────────────────────────────────────────
// 走訪規則 (排除 .obsidian/node_modules 等) 集中於 vault-walk.mjs 單一來源。
// 2026-10-01: 本檔曾無排除清單 → 掃進 Obsidian plugin 的 node_modules,
// Hatch 孵化 2043 分身 (真實業務量 366), 分身命名空間被第三方套件 README 佔據。

// ── Absorb: 標變體 (正確/錯誤) ─────────────────────────────────
function classify(node, fileBody) {
  // 錯誤變體信號
  const wrong = /(誤|錯|反證|推翻|假說|myth|wrong|incorrect|deprecated)/i.test(node.text + fileBody.slice(0, 400));
  return { correct: !wrong, variant: wrong ? 'incorrect' : 'correct' };
}

// ── Feedback + Project: 反饋 MOC + 標投向本體 ──────────────────
function feedbackToMOC(avatars) {
  const idx = path.join(VAULT, 'Agents/context/00-Index.md');
  if (!fs.existsSync(idx)) return;
  let s = fs.readFileSync(idx, 'utf8');
  const count = avatars.length;
  const absorbed = avatars.filter(a => a.absorbed).length;
  const line = `\n> 萬能知識分身迴路: ${count} 結點孵化, ${absorbed} 已吸收反饋本體 (零時差)\n`;
  if (!s.includes('萬能知識分身迴路')) s = s.replace(/(#.*第二大腦.*\n)/, `$1${line}`);
  else s = s.replace(/> 萬能知識分身迴路:.*\n/, line.trim() + '\n');
  fs.writeFileSync(idx, s);
}

// ── Project: 萃取型別變體 → canonical 片段 (C 線) ──────────────
function extractAvatarTypes(avatars) {
  // 分身跟隨的知識點若含 TS 型別宣告, 萃取供 sync-vault-types 消費
  const out = ['// AUTO-GENERATED by knowledge-avatar.mjs — 萬能知識分身型別投影',
    '// 零時差投向本體: 經 sync-vault-types.ts 萃取進 shared/types.ts', ''];
  const seen = new Set();
  for (const av of avatars) {
    const fp = path.join(VAULT, av.file);
    const s = fs.readFileSync(fp, 'utf8');
    const m = s.match(/export\s+(type|interface|enum)\s+([A-Za-z0-9_]+)/);
    if (m && !seen.has(m[2])) {
      seen.add(m[2]);
      const block = s.match(new RegExp(`export\\s+${m[1]}\\s+${m[2]}[\\s\\S]*?\\n}`, 'm'));
      if (block) out.push(`// [avatar:${av.node}] correct=${av.correct}`, block[0], '');
    }
  }
  return out.join('\n');
}

// ── main ───────────────────────────────────────────────────────
function main() {
  const nodes = collectNodes(VAULT);
  const registry = {};
  const avatars = [];
  for (const n of nodes) {
    // id 必須涵蓋出處 (file + type) 與文字: 只用文字會讓不同檔案裡的同名結點
    // (例: "相關" / "TypeMatrix") 撞同一 base64 前綴, 366 結點塌成 220 (損 40%)。
    const key = `${n.file}\0${n.type}\0${n.text}`;
    const id = createHash('sha1').update(key, 'utf8').digest('hex').slice(0, 16);
    const fileBody = fs.readFileSync(path.join(VAULT, n.file), 'utf8');
    const cls = classify(n, fileBody);
    const av = {
      id,
      node: n.text,
      type: n.type,
      file: n.file,
      correct: cls.correct,
      variant: cls.variant,
      absorbed: true,          // 單結點當下即吸收完 (零時差)
      projected_to_ontology: true, // 瞬間投向本體
    };
    registry[id] = av;
    avatars.push(av);
  }
  const keys = Object.keys(registry);
  if (keys.length !== avatars.length) {
    throw new Error(
      `registry 塌縮: 收集 ${avatars.length} 結點只存進 ${keys.length} 個 id — ` +
      `id 生成器仍有碰撞 (回報 exit 1, 禁止靜默丟資料)`
    );
  }
  fs.writeFileSync(REG, JSON.stringify(registry, null, 2));
  feedbackToMOC(avatars);

  // C 線: 萃取型別變體 → .avatar-types.d.ts (sync-vault-types 自動接 canonical)
  const typeFrag = extractAvatarTypes(avatars);
  const TYPE_F = path.join(VAULT, 'Agents/context/.avatar-types.d.ts');
  fs.writeFileSync(TYPE_F, typeFrag);

  const corrected = avatars.filter(a => a.correct).length;
  const wrong = avatars.length - corrected;
  console.log(`[Avatar] 孵化 ${avatars.length} 分身`);
  console.log(`[Avatar] 正確變體 ${corrected} / 錯誤變體 ${wrong} (皆保留, 當下最完整)`);
  console.log(`[Avatar] 全數 absorbed + projected_to_ontology (零時差)`);
  console.log(`[Avatar] 型別投影 → ${path.relative(process.cwd(), TYPE_F)} (sync-vault-types 接管)`);
  console.log(`[Avatar] registry → ${path.relative(process.cwd(), REG)}`);
}

main();
